package interfaces;

/**
 * Interface Trainable
 * 
 * Konsep OOP: INTERFACE
 * Mendefinisikan kontrak perilaku latihan (training) yang harus diimplementasikan
 * oleh setiap class pemain sepak bola.
 */
public interface Trainable {

    /**
     * Method abstrak untuk menjalankan aktivitas latihan sesuai posisi pemain.
     */
    void train();
}
